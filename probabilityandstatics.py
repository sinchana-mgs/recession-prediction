import pandas as pd, numpy as np, datetime as dt, matplotlib.pyplot as plt
from pandas_datareader import data as pdr
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from statsmodels.tsa.arima.model import ARIMA
import warnings; warnings.filterwarnings("ignore")

# ---------------- Helper Functions ----------------
def make_lags(df, cols, lags=[1,2,4]):
    for c in cols:
        for l in lags:
            df[f"{c}_lag{l}"] = df[c].shift(l)
    return df

def forecast_series(series, steps=8):
    """Forecast next `steps` periods with ARIMA(1,1,0)."""
    try:
        model = ARIMA(series, order=(1,1,0))
        fit = model.fit()
        f = fit.forecast(steps=steps)
    except:
        f = pd.Series([series.iloc[-1]]*steps)
    return f

def run_country(name, series_codes):
    print(f"\n===== {name.upper()} =====")
    start, end = dt.datetime(1970,1,1), dt.datetime(2025,12,31)
    df=None
    for label, code in series_codes.items():
        try:
            temp = pdr.DataReader(code, "fred", start, end)
            temp.columns=[label]
            df = temp if df is None else df.join(temp, how="outer")
        except:
            print(f"⚠️ Could not load {label} for {name}. Skipping.")
    if df is None or df.empty:
        print(f"❌ No data for {name}. Skipping this country.")
        return None

    df=df.resample("QE").mean().dropna()
    features=[c for c in df.columns if c!="RECESSION"]
    df=make_lags(df,features).dropna()

    X=df[[c for c in df.columns if "lag" in c]]
    y=df["RECESSION"].astype(int)
    split=int(0.8*len(df))
    X_train,X_test=X.iloc[:split],X.iloc[split:]
    y_train,y_test=y.iloc[:split],y.iloc[split:]

    scaler=StandardScaler().fit(X_train)
    Xs_train,Xs_test=scaler.transform(X_train),scaler.transform(X_test)

    model=LogisticRegression(max_iter=1000)
    model.fit(Xs_train,y_train)
    auc=roc_auc_score(y_test,model.predict_proba(Xs_test)[:,1]) if len(np.unique(y_test))>1 else np.nan
    print(f"Validation AUC: {auc:.3f}")

    # Forecast 8 quarters (2 years)
    future_dict={c:forecast_series(df[c].dropna(),steps=8) for c in features}
    future_df=pd.DataFrame(future_dict)
    future_df.index=pd.date_range(df.index[-1]+pd.offsets.QuarterBegin(),periods=8,freq="QE")
    df_ext=pd.concat([df[features+["RECESSION"]],future_df])
    df_ext = make_lags(df_ext, features).ffill()

    X_future=df_ext.loc[df_ext.index>=future_df.index[0],[c for c in df_ext.columns if "lag" in c]]
    X_future_s=scaler.transform(X_future)
    probs=model.predict_proba(X_future_s)[:,1]
    idx=X_future.index
    mean_prob=float(np.mean(probs))

    # --- Graph 1: Recession Probability ---
    plt.figure(figsize=(8,3))
    plt.plot(idx, probs, marker='o', color="blue")
    plt.title(f"{name}: Recession Probability (Next 2 Years)")
    plt.ylabel("Probability"); plt.grid(True); plt.tight_layout(); plt.show()

    # --- Graph 2: Feature Importance ---
    importance=pd.Series(model.coef_[0],index=X.columns)
    top_feats=importance.abs().sort_values(ascending=False).head(8)
    plt.figure(figsize=(6,3))
    top_feats.plot(kind="barh",color="teal")
    plt.title(f"{name}: Top Feature Importances")
    plt.xlabel("Absolute Coefficient"); plt.tight_layout(); plt.show()

    # --- Graph 3: Economic Indicator Forecasts ---
    future_df.plot(subplots=True, figsize=(8,6), title=f"{name}: Forecasted Economic Indicators")
    plt.tight_layout(); plt.show()

    # --- Textual Explainability ---
    print("Top Drivers of Recession Risk:")
    for feat in top_feats.index:
        if "GDP" in feat: print(f"• {feat}: Weak GDP growth contributes to higher risk.")
        elif "UNRATE" in feat: print(f"• {feat}: Rising unemployment signals slowing demand.")
        elif "CPI" in feat: print(f"• {feat}: Inflation reduces real spending power.")
        elif "FEDFUNDS" in feat or "ECB" in feat: print(f"• {feat}: High interest rates tighten credit.")
        elif "SP500" in feat or "STOCK" in feat: print(f"• {feat}: Falling stock market reduces investor confidence.")

    # Macro Trend Summary
    for c in features:
        change=((future_df[c].iloc[-1]-future_df[c].iloc[0])/future_df[c].iloc[0])*100
        direction="rising" if change>0 else "falling"
        print(f"• {c}: {direction} by {abs(change):.2f}%")

    if mean_prob>0.6:
        print(f"\n⚠️ {name}: High recession risk — may lead global downturn.")
    elif mean_prob>0.3:
        print(f"\n🟠 {name}: Moderate risk — watch for inflation and policy tightening.")
    else:
        print(f"\n🟢 {name}: Low recession risk — stable indicators.")

    return mean_prob

